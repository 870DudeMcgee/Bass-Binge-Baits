const moneyFormatter = new Intl.NumberFormat('en-US', {
  style: 'currency',
  currency: 'USD'
});

const cartState = {
  items: loadCart()
};

const cartDrawer = document.querySelector('[data-cart-drawer]');
const cartOverlay = document.querySelector('[data-cart-overlay]');
const cartItemsNode = document.querySelector('[data-cart-items]');
const cartEmptyNode = document.querySelector('[data-cart-empty]');
const cartSubtotalNode = document.querySelector('[data-cart-subtotal]');
const checkoutLink = document.querySelector('[data-checkout-link]');
const toastNode = document.querySelector('[data-toast]');
const productSearch = document.querySelector('[data-product-search]');
const productEmpty = document.querySelector('[data-shop-empty]');
const filterButtons = Array.from(document.querySelectorAll('[data-product-filter]'));
let activeFilter = 'all';
let toastTimer;

function formatMoney(value) {
  return moneyFormatter.format(Number(value || 0));
}

function loadCart() {
  try {
    const saved = JSON.parse(localStorage.getItem(SHOPIFY_STORE.cartStorageKey));
    return Array.isArray(saved) ? saved.filter((item) => item.variantId && item.quantity > 0) : [];
  } catch (error) {
    return [];
  }
}

function saveCart() {
  localStorage.setItem(SHOPIFY_STORE.cartStorageKey, JSON.stringify(cartState.items));
}

function getProduct(productKey) {
  return SHOPIFY_STORE.products.find((product) => product.key === productKey);
}

function getVariant(product, variantId) {
  return product?.variants.find((variant) => String(variant.id) === String(variantId));
}

function getCartLine(item) {
  const product = getProduct(item.productKey);
  const variant = getVariant(product, item.variantId);

  if (!product || !variant) {
    return null;
  }

  return {
    ...item,
    product,
    variant,
    lineTotal: variant.price * item.quantity
  };
}

function getCartLines() {
  return cartState.items.map(getCartLine).filter(Boolean);
}

function getCartQuantity() {
  return cartState.items.reduce((total, item) => total + item.quantity, 0);
}

function getCartSubtotal() {
  return getCartLines().reduce((total, line) => total + line.lineTotal, 0);
}

function setQuantity(productKey, variantId, quantity) {
  const normalizedQuantity = Math.max(0, Math.min(99, Number(quantity) || 0));
  const itemIndex = cartState.items.findIndex(
    (item) => item.productKey === productKey && String(item.variantId) === String(variantId)
  );

  if (normalizedQuantity === 0) {
    if (itemIndex >= 0) {
      cartState.items.splice(itemIndex, 1);
    }
  } else if (itemIndex >= 0) {
    cartState.items[itemIndex].quantity = normalizedQuantity;
  } else {
    cartState.items.push({ productKey, variantId, quantity: normalizedQuantity });
  }

  saveCart();
  renderCart();
}

function addToCart(productKey, variantId, quantity) {
  const current = cartState.items.find(
    (item) => item.productKey === productKey && String(item.variantId) === String(variantId)
  );
  const nextQuantity = (current?.quantity || 0) + Math.max(1, Number(quantity) || 1);
  setQuantity(productKey, variantId, nextQuantity);

  const product = getProduct(productKey);
  const variant = getVariant(product, variantId);
  showToast(`${variant.title} added to cart`);
}

function buildCheckoutUrl() {
  const cartPath = cartState.items.map((item) => `${item.variantId}:${item.quantity}`).join(',');
  return `https://${SHOPIFY_STORE.domain}/cart/${cartPath}`;
}

function hasStorefrontToken() {
  return SHOPIFY_STORE.storefrontAccessToken.trim().length > 0;
}

async function shopifyGraphql(query, variables) {
  const response = await fetch(`https://${SHOPIFY_STORE.domain}/api/${SHOPIFY_STORE.apiVersion}/graphql.json`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-Shopify-Storefront-Access-Token': SHOPIFY_STORE.storefrontAccessToken
    },
    body: JSON.stringify({ query, variables })
  });

  if (!response.ok) {
    throw new Error(`Shopify Storefront API returned ${response.status}`);
  }

  const payload = await response.json();

  if (payload.errors?.length) {
    throw new Error(payload.errors[0].message);
  }

  return payload.data;
}

async function createStorefrontCheckoutUrl() {
  const data = await shopifyGraphql(
    `mutation CreateBassBingeCart($input: CartInput!) {
      cartCreate(input: $input) {
        cart {
          checkoutUrl
        }
        userErrors {
          field
          message
        }
      }
    }`,
    {
      input: {
        lines: cartState.items.map((item) => ({
          merchandiseId: `gid://shopify/ProductVariant/${item.variantId}`,
          quantity: item.quantity
        })),
        attributes: [
          {
            key: 'source',
            value: 'Bass Binge Website'
          }
        ]
      }
    }
  );

  const userError = data.cartCreate.userErrors[0];

  if (userError) {
    throw new Error(userError.message);
  }

  return data.cartCreate.cart.checkoutUrl;
}

function updateCartBadges() {
  const quantity = getCartQuantity();
  const label = quantity === 1 ? '1 item' : `${quantity} items`;

  document.querySelectorAll('[data-cart-count]').forEach((node) => {
    node.textContent = String(quantity);
    node.classList.toggle('has-items', quantity > 0);
  });

  document.querySelectorAll('[data-cart-summary-count]').forEach((node) => {
    node.textContent = label;
  });
}

function renderCart() {
  const lines = getCartLines();
  const isEmpty = lines.length === 0;

  updateCartBadges();
  cartEmptyNode.hidden = !isEmpty;
  cartItemsNode.hidden = isEmpty;
  cartItemsNode.innerHTML = '';

  lines.forEach((line) => {
    const itemNode = document.createElement('article');
    itemNode.className = 'cart-item';
    itemNode.innerHTML = `
      <img src="${line.variant.image}" alt="${line.product.title} in ${line.variant.title}" loading="lazy" />
      <div class="cart-item-main">
        <div class="cart-item-top">
          <div>
            <h3>${line.product.title}</h3>
            <p>${line.variant.title}</p>
          </div>
          <strong>${formatMoney(line.lineTotal)}</strong>
        </div>
        <div class="cart-item-actions">
          <div class="quantity-stepper compact" aria-label="Quantity for ${line.product.title} in ${line.variant.title}">
            <button type="button" data-cart-decrease aria-label="Decrease quantity">-</button>
            <span>${line.quantity}</span>
            <button type="button" data-cart-increase aria-label="Increase quantity">+</button>
          </div>
          <button class="text-button" type="button" data-cart-remove>Remove</button>
        </div>
      </div>
    `;

    itemNode.querySelector('[data-cart-decrease]').addEventListener('click', () => {
      setQuantity(line.product.key, line.variant.id, line.quantity - 1);
    });

    itemNode.querySelector('[data-cart-increase]').addEventListener('click', () => {
      setQuantity(line.product.key, line.variant.id, line.quantity + 1);
    });

    itemNode.querySelector('[data-cart-remove]').addEventListener('click', () => {
      setQuantity(line.product.key, line.variant.id, 0);
    });

    cartItemsNode.appendChild(itemNode);
  });

  cartSubtotalNode.textContent = formatMoney(getCartSubtotal());
  checkoutLink.href = isEmpty ? '#' : buildCheckoutUrl();
  checkoutLink.setAttribute('aria-disabled', String(isEmpty));
  checkoutLink.classList.toggle('disabled', isEmpty);
}

function openCart() {
  cartDrawer.setAttribute('aria-hidden', 'false');
  cartOverlay.hidden = false;
  document.body.classList.add('cart-open');
  setTimeout(() => cartDrawer.querySelector('[data-cart-close]')?.focus(), 50);
}

function closeCart() {
  cartDrawer.setAttribute('aria-hidden', 'true');
  cartOverlay.hidden = true;
  document.body.classList.remove('cart-open');
}

function showToast(message) {
  if (!toastNode) {
    return;
  }

  toastNode.textContent = message;
  toastNode.classList.add('visible');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toastNode.classList.remove('visible'), 2600);
}

function createProductControls(card, product, link) {
  const mediaImage = card.querySelector('.product-media img');
  const priceNode = card.querySelector('.product-price');
  const controls = document.createElement('div');
  const selectId = `variant-${product.key}`;

  controls.className = 'product-selector';
  controls.innerHTML = `
    <div class="variant-swatches" data-variant-swatches></div>
    <label class="field-label" for="${selectId}">
      Color
      <select id="${selectId}" data-variant-select></select>
    </label>
    <div class="product-purchase-row">
      <div class="quantity-stepper" aria-label="Product quantity">
        <button type="button" data-quantity-decrease aria-label="Decrease quantity">-</button>
        <input type="number" inputmode="numeric" min="1" max="99" value="1" data-quantity-input aria-label="Quantity" />
        <button type="button" data-quantity-increase aria-label="Increase quantity">+</button>
      </div>
      <button class="btn btn-primary add-cart-button" type="button" data-add-to-cart>Add to Cart</button>
    </div>
    <button class="text-button product-detail-link" type="button" data-view-product>View selected color</button>
  `;

  const select = controls.querySelector('[data-variant-select]');
  const swatches = controls.querySelector('[data-variant-swatches]');
  const quantityInput = controls.querySelector('[data-quantity-input]');
  const addButton = controls.querySelector('[data-add-to-cart]');
  const viewButton = controls.querySelector('[data-view-product]');

  product.variants.forEach((variant, index) => {
    const option = document.createElement('option');
    option.value = String(variant.id);
    option.textContent = variant.available ? variant.title : `${variant.title} - Sold out`;
    option.disabled = !variant.available;
    select.appendChild(option);

    const swatch = document.createElement('button');
    swatch.className = 'swatch-button';
    swatch.type = 'button';
    swatch.style.setProperty('--swatch', variant.swatch);
    swatch.dataset.variantId = String(variant.id);
    swatch.setAttribute('aria-label', `Select ${variant.title}`);
    swatch.setAttribute('aria-pressed', String(index === 0));
    swatch.disabled = !variant.available;
    swatch.innerHTML = '<span></span>';
    swatches.appendChild(swatch);
  });

  function getSelectedVariant() {
    return getVariant(product, select.value) || product.variants.find((variant) => variant.available) || product.variants[0];
  }

  function updateSelectedVariant() {
    const selected = getSelectedVariant();

    select.value = String(selected.id);
    mediaImage.src = selected.image;
    mediaImage.alt = `${product.title} in ${selected.title}`;
    priceNode.textContent = formatMoney(selected.price);
    addButton.disabled = !selected.available;
    viewButton.textContent = `View ${selected.title}`;

    swatches.querySelectorAll('[data-variant-id]').forEach((swatch) => {
      swatch.setAttribute('aria-pressed', String(swatch.dataset.variantId === String(selected.id)));
    });
  }

  controls.querySelector('[data-quantity-decrease]').addEventListener('click', () => {
    quantityInput.value = String(Math.max(1, Number(quantityInput.value) - 1 || 1));
  });

  controls.querySelector('[data-quantity-increase]').addEventListener('click', () => {
    quantityInput.value = String(Math.min(99, Number(quantityInput.value) + 1 || 2));
  });

  quantityInput.addEventListener('input', () => {
    quantityInput.value = String(Math.max(1, Math.min(99, Number(quantityInput.value) || 1)));
  });

  select.addEventListener('change', updateSelectedVariant);

  swatches.addEventListener('click', (event) => {
    const swatch = event.target.closest('[data-variant-id]');

    if (!swatch) {
      return;
    }

    select.value = swatch.dataset.variantId;
    updateSelectedVariant();
  });

  addButton.addEventListener('click', () => {
    const selected = getSelectedVariant();
    addToCart(product.key, selected.id, quantityInput.value);
    openCart();
  });

  viewButton.addEventListener('click', () => {
    const selected = getSelectedVariant();
    window.open(`https://${SHOPIFY_STORE.domain}/products/${product.handle}?variant=${selected.id}`, '_blank', 'noopener');
  });

  link.replaceWith(controls);
  card.dataset.productSearch = product.search;
  updateSelectedVariant();
}

function setupProductCards() {
  document.querySelectorAll('[data-shopify-product]').forEach((link) => {
    const product = getProduct(link.getAttribute('data-shopify-product'));
    const card = link.closest('.product-card');

    if (!product || !card) {
      return;
    }

    createProductControls(card, product, link);
  });
}

function applyProductFilters() {
  const query = productSearch?.value.trim().toLowerCase() || '';
  let visibleCount = 0;

  document.querySelectorAll('.product-card').forEach((card) => {
    const haystack = `${card.textContent} ${card.dataset.productSearch || ''}`.toLowerCase();
    const matchesSearch = !query || haystack.includes(query);
    const matchesFilter = activeFilter === 'all' || haystack.includes(activeFilter);
    const isVisible = matchesSearch && matchesFilter;

    card.hidden = !isVisible;
    visibleCount += isVisible ? 1 : 0;
  });

  if (productEmpty) {
    productEmpty.hidden = visibleCount > 0;
  }
}

setupProductCards();
renderCart();

document.querySelectorAll('[data-cart-open]').forEach((button) => {
  button.addEventListener('click', openCart);
});

document.querySelectorAll('[data-cart-close]').forEach((button) => {
  button.addEventListener('click', closeCart);
});

cartOverlay?.addEventListener('click', closeCart);

checkoutLink?.addEventListener('click', async (event) => {
  if (cartState.items.length === 0) {
    event.preventDefault();
    return;
  }

  if (!hasStorefrontToken()) {
    return;
  }

  event.preventDefault();
  checkoutLink.textContent = 'Preparing Checkout';
  checkoutLink.classList.add('is-loading');
  checkoutLink.setAttribute('aria-disabled', 'true');

  try {
    window.location.href = await createStorefrontCheckoutUrl();
  } catch (error) {
    showToast('Opening secure checkout');
    window.location.href = buildCheckoutUrl();
  } finally {
    checkoutLink.textContent = 'Secure Checkout';
    checkoutLink.classList.remove('is-loading');
    checkoutLink.setAttribute('aria-disabled', 'false');
  }
});

productSearch?.addEventListener('input', applyProductFilters);

filterButtons.forEach((button) => {
  button.addEventListener('click', () => {
    activeFilter = button.dataset.productFilter;
    filterButtons.forEach((filterButton) => {
      filterButton.classList.toggle('active', filterButton === button);
    });
    applyProductFilters();
  });
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && cartDrawer?.getAttribute('aria-hidden') === 'false') {
    closeCart();
  }
});
